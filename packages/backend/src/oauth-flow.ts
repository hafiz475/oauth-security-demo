import { createHash, randomBytes, randomUUID } from 'node:crypto';
import type { Db } from './db/index.js';
import type { AppContext } from './context.js';
import type { Provider } from './provider-registry.js';
import type { Identity } from './session.js';
import { decrypt, encrypt } from './crypto.js';
import { HttpError } from './http-error.js';
import { newState, verifyState } from './state.js';

export const FLOW_TTL_MS = 10 * 60 * 1000;
const CLIENT_NONCE_SHAPE = /^[A-Za-z0-9_-]{16,64}$/;

export interface FlowRow {
  payload_id: string;
  provider: string;
  session_id: string;
  business_uid: string;
  member_id: string;
  state: string;
  verifier_cipher: string | null;
  redirect_uri: string;
  created_at: number;
  expires_at: number;
  consumed_at: number | null;
}

export interface StartFlowInput {
  provider: Provider;
  identity: Identity;
  redirectUri: string;
  /**
   * Optional per-tab nonce generated by the SPA. It is appended to the state
   * so the tab that started a full-page redirect can recognise its own return.
   */
  clientNonce?: string;
}

const base64url = (buf: Buffer) => buf.toString('base64url');
export const pkceChallenge = (verifier: string) => base64url(createHash('sha256').update(verifier).digest());

export function createFlowStore(db: Db, now: () => number) {
  const candidates = (identity: Identity, providers: string[]) =>
    db
      .prepare(
        `SELECT * FROM oauth_flows
         WHERE session_id = ? AND consumed_at IS NULL AND expires_at > ?
           AND provider IN (${providers.map(() => '?').join(',')})`,
      )
      .all(identity.sessionId, now(), ...providers) as FlowRow[];

  // Compare against every candidate so timing does not reveal which one matched.
  const match = (rows: FlowRow[], state: unknown) => {
    let found: FlowRow | undefined;
    for (const row of rows) if (verifyState(row.state, state)) found = row;
    return found;
  };

  return {
    start({ provider, identity, redirectUri, clientNonce }: StartFlowInput) {
      if (clientNonce !== undefined && !CLIENT_NONCE_SHAPE.test(clientNonce)) {
        throw new HttpError(400, 'invalid_client_nonce');
      }
      const payloadId = randomUUID();
      const state = clientNonce ? `${newState()}.${clientNonce}` : newState();
      const verifier = provider.requiresPKCE ? base64url(randomBytes(32)) : undefined;
      const t = now();
      db.prepare(
        `INSERT INTO oauth_flows
           (payload_id, provider, session_id, business_uid, member_id, state, verifier_cipher, redirect_uri, created_at, expires_at)
         VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
      ).run(
        payloadId,
        provider.id,
        identity.sessionId,
        identity.businessUid,
        identity.memberId,
        state,
        verifier ? encrypt(verifier) : null,
        redirectUri,
        t,
        t + FLOW_TTL_MS,
      );
      return { payloadId, state };
    },

    /** The not-yet-used flow a popup launch URL refers to, if it belongs to this session. */
    findForLaunch(payloadId: unknown, identity: Identity, providerId: string): FlowRow | undefined {
      if (typeof payloadId !== 'string') return undefined;
      return db
        .prepare(
          `SELECT * FROM oauth_flows
           WHERE payload_id = ? AND session_id = ? AND provider = ? AND consumed_at IS NULL AND expires_at > ?`,
        )
        .get(payloadId, identity.sessionId, providerId, now()) as FlowRow | undefined;
    },

    /** Checks a returned state without consuming it. */
    peek(identity: Identity, providers: string[], state: unknown): FlowRow | undefined {
      return match(candidates(identity, providers), state);
    },

    /** Verifies and consumes a returned state. Exactly one caller can win. */
    claim(identity: Identity, providers: string[], state: unknown): FlowRow | undefined {
      const row = match(candidates(identity, providers), state);
      if (!row) return undefined;
      const res = db
        .prepare('UPDATE oauth_flows SET consumed_at = ? WHERE payload_id = ? AND consumed_at IS NULL')
        .run(now(), row.payload_id);
      return res.changes === 1 ? row : undefined;
    },

    codeVerifier(row: FlowRow): string | undefined {
      return row.verifier_cipher ? decrypt(row.verifier_cipher) : undefined;
    },
  };
}

export type FlowStore = ReturnType<typeof createFlowStore>;

export function buildAuthorizeUrl(ctx: AppContext, provider: Provider, flow: FlowRow): string {
  const url = new URL(provider.authUrl);
  url.searchParams.set('response_type', 'code');
  url.searchParams.set('client_id', provider.clientId);
  url.searchParams.set('redirect_uri', flow.redirect_uri);
  url.searchParams.set('scope', provider.scopes.join(' '));
  url.searchParams.set('state', flow.state);
  const verifier = ctx.flows.codeVerifier(flow);
  if (verifier) {
    url.searchParams.set('code_challenge', pkceChallenge(verifier));
    url.searchParams.set('code_challenge_method', 'S256');
  }
  return url.toString();
}

export interface TokenSet {
  accessToken: string;
  refreshToken: string | undefined;
  expiresIn: number | undefined;
}

/** Server-to-server code exchange (RFC 6749 §4.1.3, form-encoded body). */
export async function exchangeCode(ctx: AppContext, provider: Provider, flow: FlowRow, code: string): Promise<TokenSet> {
  const form = new URLSearchParams({
    grant_type: 'authorization_code',
    code,
    redirect_uri: flow.redirect_uri,
    client_id: provider.clientId,
  });
  if (provider.clientSecret) form.set('client_secret', provider.clientSecret);
  const verifier = ctx.flows.codeVerifier(flow);
  if (verifier) form.set('code_verifier', verifier);

  const res = await ctx.cfg.fetch(provider.tokenUrl, {
    method: 'POST',
    headers: { 'content-type': 'application/x-www-form-urlencoded', accept: 'application/json' },
    body: form.toString(),
  });
  if (!res.ok) throw new HttpError(502, 'token_exchange_failed');
  const body = (await res.json()) as Record<string, unknown>;
  if (typeof body.access_token !== 'string') throw new HttpError(502, 'token_exchange_failed');
  return {
    accessToken: body.access_token,
    refreshToken: typeof body.refresh_token === 'string' ? body.refresh_token : undefined,
    expiresIn: typeof body.expires_in === 'number' ? body.expires_in : undefined,
  };
}

/** Provider error codes are echoed to the UI only if they look like codes. */
export const safeErrorCode = (value: unknown) =>
  typeof value === 'string' && /^[a-z_]{1,64}$/.test(value) ? value : 'provider_error';
